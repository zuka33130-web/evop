export const generateGodModeMonitorPs1 = (): string => {
  return [
    '#Requires -RunAsAdministrator',
    '# ============================================================',
    '#  CS2 GOD MODE MONITOR v1 - PN64 i3-1220P',
    '#  Loguea: reloj CPU real, uso CPU, GPU 3D, RAM, temperatura',
    '#  Detecta throttling en vivo + resumen diagnostico al salir',
    '# ============================================================',
    'param(',
    '    [int]$IntervalMs = 1000,',
    '    [string]$LogDir = "$env:USERPROFILE\\Desktop\\CS2_Logs"',
    ')',
    '$ErrorActionPreference = \'SilentlyContinue\'',
    'New-Item -ItemType Directory -Path $LogDir -Force | Out-Null',
    '$stamp = Get-Date -Format "yyyy-MM-dd_HH-mm"',
    '$csv = Join-Path $LogDir "CS2_Session_$stamp.csv"',
    '',
    'Write-Host "== CS2 GOD MODE MONITOR ==" -ForegroundColor Cyan',
    'Write-Host "Esperando a cs2.exe... (se activa solo al detectar el juego)"',
    '',
    '$waited = 0',
    'while (-not (Get-Process cs2 -EA SilentlyContinue)) {',
    '    Start-Sleep -Seconds 2; $waited += 2',
    '    if ($waited -ge 600) { Write-Host "CS2 no detectado en 10 min. Saliendo."; exit }',
    '}',
    'Write-Host "CS2 detectado. MONITOREANDO -> $csv" -ForegroundColor Green',
    '',
    '# Calentar contadores (la 1ra lectura siempre es calibracion)',
    'Get-Counter \'\\Processor Information(_Total)\\% Processor Performance\' | Out-Null',
    'Get-Counter \'\\Processor Information(_Total)\\% Processor Time\' | Out-Null',
    'Get-Counter \'\\GPU Engine(*engtype_3D)\\Utilization Percentage\' | Out-Null',
    'Get-Counter \'\\Process(cs2)\\% Processor Time\' | Out-Null',
    '',
    '"Timestamp,CPUClockPct,CPUTimePct,CS2_CPUPct,GPU3DPct,RAMDispoMB,TempC,Throttle" | Out-File $csv -Encoding UTF8',
    '',
    '$throttleCount = 0; $samples = 0',
    '',
    'while (Get-Process cs2 -EA SilentlyContinue) {',
    '    $cpuPerf = [math]::Round(((Get-Counter \'\\Processor Information(_Total)\\% Processor Performance\').CounterSamples.CookedValue), 1)',
    '    $cpuTime = [math]::Round(((Get-Counter \'\\Processor Information(_Total)\\% Processor Time\').CounterSamples.CookedValue), 1)',
    '    $gpu     = [math]::Round((((Get-Counter \'\\GPU Engine(*engtype_3D)\\Utilization Percentage\').CounterSamples | Measure-Object CookedValue -Sum).Sum), 1)',
    '    $ram     = [math]::Round(((Get-Counter \'\\Memory\\Available MBytes\').CounterSamples.CookedValue), 0)',
    '    $cs2cpu  = [math]::Round(((Get-Counter \'\\Process(cs2)\\% Processor Time\').CounterSamples.CookedValue) / 12, 1)',
    '',
    '    $temp = 0',
    '    $tz = (Get-Counter \'\\Thermal Zone Information(*)\\Temperature\').CounterSamples',
    '    if ($tz) { $temp = [math]::Round((($tz | Measure-Object CookedValue -Maximum).Maximum / 10) - 273.15, 1) }',
    '',
    '    # Throttling: el reloj cae bajo carga, o temperatura critica',
    '    $throttle = 0',
    '    if (($cpuPerf -lt 95 -and $cpuTime -gt 30) -or $temp -ge 95) { $throttle = 1; $throttleCount++ }',
    '    $samples++',
    '',
    '    "$(Get-Date -Format \'HH:mm:ss\'),$cpuPerf,$cpuTime,$cs2cpu,$gpu,$ram,$temp,$throttle" | Out-File $csv -Append -Encoding UTF8',
    '',
    '    $color = \'Green\'',
    '    if ($temp -ge 85 -or $cpuPerf -lt 100) { $color = \'Yellow\' }',
    '    if ($temp -ge 95 -or $cpuPerf -lt 90)  { $color = \'Red\' }',
    '    Write-Host ("`r[$(Get-Date -Format \'HH:mm:ss\')] CLK:$cpuPerf% CPU:$cpuTime% CS2:$cs2cpu% GPU:$gpu% RAM:$ram MB TEMP:$temp C   ") -ForegroundColor $color -NoNewline',
    '',
    '    Start-Sleep -Milliseconds $IntervalMs',
    '}',
    '',
    '# ===== RESUMEN DIAGNOSTICO POST-PARTIDA =====',
    '$data = Import-Csv $csv',
    '$temps = @($data | ForEach-Object { [double]$_.TempC })',
    '$clks  = @($data | ForEach-Object { [double]$_.CPUClockPct })',
    '$gpus  = @($data | ForEach-Object { [double]$_.GPU3DPct })',
    '$maxTemp = if ($temps.Count) { ($temps | Measure-Object -Maximum).Maximum } else { 0 }',
    '$avgTemp = if ($temps.Count) { [math]::Round(($temps | Measure-Object -Average).Average, 1) } else { 0 }',
    '$avgClk  = [math]::Round(($clks | Measure-Object -Average).Average, 1)',
    '$avgGpu  = [math]::Round(($gpus | Measure-Object -Average).Average, 1)',
    '$thrPct  = if ($samples -gt 0) { [math]::Round($throttleCount / $samples * 100, 1) } else { 0 }',
    '',
    '$diag = ""',
    'if ($maxTemp -ge 95) { $diag += "- THERMAL THROTTLING: mejora refrigeracion o BAJA PL1 en ThrottleStop`n" }',
    'if ($avgGpu -ge 95)  { $diag += "- GPU-BOUND: baja resolucion o sube FSR a Rendimiento`n" }',
    'if ($avgGpu -lt 85 -and $avgClk -ge 95) { $diag += "- CPU-BOUND leve: cierra overlays, revisa EPP=0 en ThrottleStop`n" }',
    'if ($thrPct -lt 2 -and $maxTemp -lt 90) { $diag += "- SISTEMA SANO: tienes margen para SUBIR PL1 en ThrottleStop`n" }',
    '',
    '$sum = @"',
    '',
    '==== RESUMEN SESION CS2 - $stamp ====',
    'Muestras: $samples',
    'Temp media / maxima: $avgTemp C / $maxTemp C',
    'Reloj CPU medio: $avgClk % del nominal',
    'Uso GPU 3D medio: $avgGpu %',
    'Tiempo en throttling: $thrPct %',
    '',
    'DIAGNOSTICO:',
    '$diag',
    '"@',
    '$sum | Out-File (Join-Path $LogDir "Resumen_$stamp.txt") -Encoding UTF8',
    'Write-Host $sum -ForegroundColor Cyan',
    'Write-Host "CSV completo guardado en: $csv"'
  ].join('\r\n');
};

